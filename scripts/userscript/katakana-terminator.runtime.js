// Generated by scripts/build-katakana-terminator-userscript.js from
// scripts/userscript/katakana-terminator.runtime.js. Derived from Arnie97/katakana-terminator (MIT).
//
// Two annotations, both through Google Translate's public key-less endpoint:
//  - katakana words get their English original (sl=ja, tl=en);
//  - kanji words in Japanese text get a reading in katakana (Google's romaji `rm` block, converted).
// Fault tolerance: every request has a deadline; endpoints that fail are put on a cool-down
// instead of being dropped for good; phrases that fail are retried with back-off; batches whose
// answer cannot be matched to the request are split in halves down to single phrases.
(function () {
    'use strict';

    var doc = document;
    var FLAG = 'katakanaTerminator';
    var RESCAN_EVENT = 'katakana-terminator-rescan';
    var root = doc.documentElement;
    if (root.dataset[FLAG]) {
        doc.dispatchEvent(new CustomEvent(RESCAN_EVENT));
        return;
    }
    root.dataset[FLAG] = '1';

    var CHUNK_SIZE = 100;
    var REQUEST_TIMEOUT_MS = 15000;
    var ENDPOINT_COOLDOWN_MS = 60000;
    var RETRY_DELAYS_MS = [3000, 10000, 30000, 120000];
    var SCAN_INTERVAL_MS = 500;
    var SEPARATOR = ' | '; // survives Google's romanization, which keeps one block per request

    var KATAKANA = /[ァ-ヺヽ-ヿ][゙゚ァ-ヿ]*[゙゚ァ-ヺー-ヿ]|[ｦ-ｯｱ-ﾝ][･-ﾟ]*[ｦ-ﾟ]/;
    // A kanji word, with up to two okurigana. A particle-looking hiragana right after the kanji
    // is not taken as okurigana (日本語を -> 日本語 + を), which is right far more often than not.
    var KANJI_WORD = /[㐀-䶿一-鿿豈-﫿々〆]+(?:[ぁ-ゖ]{1,2})?/;
    var PARTICLE_START = /^[はがをにでとのもへや]/;
    var KANA = /[ぁ-ゖァ-ヺ]/;
    var EXCLUDED_SELECTOR = 'ruby,rt,rp,script,style,noscript,select,textarea,input,template,[contenteditable="true"],[contenteditable=""]';
    var EXCLUDED_TAGS = { ruby: true, rt: true, script: true, style: true, noscript: true, select: true, textarea: true, input: true, template: true };

    // ----- transport -----------------------------------------------------------------------------

    function request(url) {
        return new Promise(function (resolve, reject) {
            var gm = typeof GM_xmlhttpRequest === 'function' ? GM_xmlhttpRequest
                : (typeof GM === 'object' && GM && typeof GM.xmlHttpRequest === 'function' ? GM.xmlHttpRequest : null);
            if (gm) {
                try {
                    gm({
                        method: 'GET',
                        url: url,
                        timeout: REQUEST_TIMEOUT_MS,
                        onload: function (response) {
                            if (response.status >= 200 && response.status < 300) resolve(response.responseText);
                            else reject(new Error('HTTP ' + response.status));
                        },
                        onerror: function () { reject(new Error('network error')); },
                        ontimeout: function () { reject(new Error('timeout')); }
                    });
                } catch (error) {
                    reject(error);
                }
                return;
            }
            var timer = setTimeout(function () { reject(new Error('timeout')); }, REQUEST_TIMEOUT_MS);
            fetch(url).then(function (response) {
                if (!response.ok) throw new Error('HTTP ' + response.status);
                return response.text();
            }).then(function (text) { clearTimeout(timer); resolve(text); },
                function (error) { clearTimeout(timer); reject(error); });
        });
    }

    function buildQueryString(params) {
        return '?' + Object.keys(params).map(function (k) {
            return encodeURIComponent(k) + '=' + encodeURIComponent(params[k]);
        }).join('&');
    }

    function trimEnd(s) {
        return String(s).replace(/\s+$/, '');
    }

    // ----- endpoints -----------------------------------------------------------------------------
    // Each endpoint: {id, url(phrases), parse(phrases, json) -> string[] (one per phrase) | throws}.

    // ----- romaji -> katakana --------------------------------------------------------------------

    var KANA_ROWS = {
        '': 'アイウエオ', k: 'カキクケコ', g: 'ガギグゲゴ', s: 'サシスセソ', z: 'ザジズゼゾ',
        t: 'タチツテト', d: 'ダヂヅデド', n: 'ナニヌネノ', h: 'ハヒフヘホ', b: 'バビブベボ',
        p: 'パピプペポ', m: 'マミムメモ', y: 'ヤ イユ エヨ', r: 'ラリルレロ', w: 'ワヰ ヱヲ'
    };
    var VOWELS = 'aiueo';
    var KANA_TABLE = {};

    (function buildKanaTable() {
        Object.keys(KANA_ROWS).forEach(function (consonant) {
            var row = KANA_ROWS[consonant].replace(/ /g, '');
            if (consonant === 'y') row = 'ヤ\u0000ユ\u0000ヨ';
            if (consonant === 'w') row = 'ワ\u0000\u0000\u0000ヲ';
            for (var i = 0; i < 5; i++) {
                if (row[i] !== undefined && row[i] !== '\u0000') KANA_TABLE[consonant + VOWELS[i]] = row[i];
            }
        });
        // Hepburn spellings that differ from the plain table.
        var special = {
            shi: 'シ', chi: 'チ', tsu: 'ツ', fu: 'フ', ji: 'ジ', n: 'ン',
            sha: 'シャ', shu: 'シュ', sho: 'ショ', she: 'シェ',
            cha: 'チャ', chu: 'チュ', cho: 'チョ', che: 'チェ',
            ja: 'ジャ', ju: 'ジュ', jo: 'ジョ', je: 'ジェ',
            fa: 'ファ', fi: 'フィ', fe: 'フェ', fo: 'フォ',
            ti: 'ティ', tu: 'トゥ', di: 'ディ', du: 'ドゥ', wi: 'ウィ', we: 'ウェ', va: 'ヴァ', vi: 'ヴィ', vu: 'ヴ', ve: 'ヴェ', vo: 'ヴォ'
        };
        Object.keys(special).forEach(function (key) { KANA_TABLE[key] = special[key]; });
        // Palatalized rows: kya, gya, nya, hya, bya, pya, mya, rya.
        var small = { a: 'ャ', u: 'ュ', o: 'ョ' };
        ['k', 'g', 'n', 'h', 'b', 'p', 'm', 'r'].forEach(function (consonant) {
            var base = KANA_TABLE[consonant + 'i'];
            Object.keys(small).forEach(function (vowel) { KANA_TABLE[consonant + 'y' + vowel] = base + small[vowel]; });
        });
    })();

    var LONG_VOWELS = { 'ā': 'a', 'ī': 'i', 'ū': 'u', 'ē': 'e', 'ō': 'o' };

    // Returns '' when `text` is not plain Hepburn romaji. Long vowels (ō, ū …) become the katakana
    // long-vowel mark, the usual way to write a reading in katakana (トーキョー).
    function romajiToKatakana(text) {
        var input = String(text).toLowerCase().replace(/[āīūēō]/g, function (c) { return LONG_VOWELS[c] + 'ー'; });
        input = input.replace(/[\s·・\-]+/g, '');
        if (!input || /[^a-zー']/.test(input)) return '';

        var out = '';
        var i = 0;
        while (i < input.length) {
            var c = input[i];
            if (c === 'ー') { out += 'ー'; i++; continue; }
            if (c === "'") { i++; continue; }
            // Doubled consonant (tt, kk, ss, and tch) -> small tsu.
            if (i + 1 < input.length && c === input[i + 1] && VOWELS.indexOf(c) < 0 && c !== 'n') { out += 'ッ'; i++; continue; }
            if (c === 't' && input.substr(i + 1, 2) === 'ch') { out += 'ッ'; i++; continue; }
            var matched = false;
            for (var len = 3; len >= 1 && !matched; len--) {
                var chunk = input.substr(i, len);
                if (chunk.length !== len || !Object.prototype.hasOwnProperty.call(KANA_TABLE, chunk)) continue;
                if (chunk === 'n' && /^[aiueoy]/.test(input.substr(i + 1, 1))) continue; // na, ni… not ン
                out += KANA_TABLE[chunk];
                i += len;
                matched = true;
            }
            if (!matched) return '';
        }
        return out;
    }

    var GTX_HOSTS = ['translate.googleapis.com', 'translate.google.com', 'translate.google.cn'];

    function gtxEnglish(host) {
        return {
            id: 'gtx-en@' + host,
            url: function (phrases) {
                return 'https://' + host + '/translate_a/single' + buildQueryString({
                    sl: 'ja', tl: 'en', dt: 't', client: 'gtx', q: trimEnd(phrases.join('\n'))
                });
            },
            parse: function (phrases, resp) {
                var byOriginal = {};
                var ordered = [];
                resp[0].forEach(function (item) {
                    if (!item || typeof item[0] !== 'string' || typeof item[1] !== 'string') return;
                    byOriginal[trimEnd(item[1])] = trimEnd(item[0]);
                    ordered.push(trimEnd(item[0]));
                });
                var matched = phrases.map(function (phrase) { return byOriginal[phrase]; });
                if (matched.every(function (value) { return typeof value === 'string'; })) return matched;
                if (ordered.length === phrases.length) return ordered; // normalized originals: go by position
                throw new Error('cannot align translations');
            }
        };
    }

    var DICT_ENGLISH = {
        // https://github.com/ssut/py-googletrans/issues/268
        id: 'dict-chrome-ex@translate.google.cn',
        url: function (phrases) {
            return 'https://translate.google.cn/translate_a/t' + buildQueryString({
                sl: 'ja', tl: 'en', dt: 't', client: 'dict-chrome-ex', q: trimEnd(phrases.join('\n'))
            });
        },
        parse: function (phrases, resp) {
            if (!resp.sentences) {
                var translated = resp[0].split('\n');
                if (translated.length !== phrases.length) throw new Error('cannot align translations');
                return translated.map(function (value) { return value.trim(); });
            }
            var byOriginal = {};
            resp.sentences.forEach(function (s) {
                if (s.orig) byOriginal[s.orig.trim()] = s.trans.trim();
            });
            var matched = phrases.map(function (phrase) { return byOriginal[phrase]; });
            if (matched.some(function (value) { return typeof value !== 'string'; })) {
                throw new Error('cannot align translations');
            }
            return matched;
        }
    };

    function gtxReading(host) {
        return {
            id: 'gtx-rm@' + host,
            url: function (phrases) {
                return 'https://' + host + '/translate_a/single' + buildQueryString({
                    sl: 'ja', tl: 'ja', dt: 'rm', client: 'gtx', q: phrases.join(SEPARATOR)
                });
            },
            parse: function (phrases, resp) {
                var block = null;
                resp[0].forEach(function (item) {
                    if (item && item[0] === null && typeof item[3] === 'string') block = item[3];
                    else if (item && item[0] === null && typeof item[2] === 'string') block = item[2];
                });
                if (block === null) throw new Error('no transliteration in response');
                var readings = block.split(/\s*\|\s*/).map(function (value) { return value.trim(); });
                if (readings.length !== phrases.length) throw new Error('cannot align readings');
                // Google answers in romaji; the label is the same reading written in katakana.
                // Anything that is not Hepburn romaji (e.g. a Chinese pinyin guess) gets no label.
                return readings.map(romajiToKatakana);
            }
        };
    }

    var ENDPOINTS = {
        english: GTX_HOSTS.map(gtxEnglish).concat([DICT_ENGLISH]),
        reading: GTX_HOSTS.map(gtxReading)
    };
    var endpointDownUntil = {}; // endpoint id -> time

    // ----- state ---------------------------------------------------------------------------------

    var queue = new Map();        // phrase -> Set<rt element> still waiting for a label
    var labels = new Map();       // "kind:phrase" -> label text
    var retryState = new Map();   // "kind:phrase" -> {attempts, notBefore}
    var inflight = new Set();     // "kind:phrase"
    var textMode = false;         // CSS ::before unusable: write the label as real text

    function kindOf(phrase) {
        return KATAKANA.test(phrase) && !/[㐀-鿿]/.test(phrase) ? 'english' : 'reading';
    }
    function keyOf(phrase) {
        return kindOf(phrase) + ':' + phrase;
    }

    function applyLabel(rt, text) {
        rt.dataset.rt = text;
        if (textMode) rt.textContent = text;
    }

    function flushPhrase(phrase) {
        var key = keyOf(phrase);
        if (!labels.has(key)) return;
        var text = labels.get(key);
        (queue.get(phrase) || new Set()).forEach(function (rt) { applyLabel(rt, text); });
        queue.delete(phrase);
        scheduleVerify();
    }

    // ----- translating ---------------------------------------------------------------------------

    function pickEndpoints(kind) {
        var now = Date.now();
        var list = ENDPOINTS[kind];
        var healthy = list.filter(function (endpoint) { return (endpointDownUntil[endpoint.id] || 0) <= now; });
        // Everything cooling down: try them all anyway rather than going silent.
        return healthy.length ? healthy : list;
    }

    function fetchLabels(kind, phrases) {
        var endpoints = pickEndpoints(kind);
        var lastError = new Error('no endpoint');
        function attempt(index) {
            if (index >= endpoints.length) return Promise.reject(lastError);
            var endpoint = endpoints[index];
            return request(endpoint.url(phrases)).then(function (text) {
                var json = JSON.parse(text.replace("'", '’'));
                return endpoint.parse(phrases, json);
            }).then(function (result) {
                delete endpointDownUntil[endpoint.id];
                return result;
            }, function (error) {
                lastError = error;
                if (!/cannot align/.test(error.message)) {
                    endpointDownUntil[endpoint.id] = Date.now() + ENDPOINT_COOLDOWN_MS;
                }
                return attempt(index + 1);
            });
        }
        return attempt(0);
    }

    function noteFailure(kind, phrase) {
        var key = kind + ':' + phrase;
        var state = retryState.get(key) || { attempts: 0, notBefore: 0 };
        state.notBefore = Date.now() + RETRY_DELAYS_MS[Math.min(state.attempts, RETRY_DELAYS_MS.length - 1)];
        state.attempts++;
        retryState.set(key, state);
    }

    function translateChunk(kind, phrases) {
        phrases.forEach(function (phrase) { inflight.add(kind + ':' + phrase); });
        return fetchLabels(kind, phrases).then(function (labelsForPhrases) {
            phrases.forEach(function (phrase, index) {
                var key = kind + ':' + phrase;
                inflight.delete(key);
                retryState.delete(key);
                if (labelsForPhrases[index]) labels.set(key, labelsForPhrases[index]);
                else labels.set(key, ''); // the service had nothing to say; do not ask again
                flushPhrase(phrase);
            });
        }, function (error) {
            phrases.forEach(function (phrase) { inflight.delete(kind + ':' + phrase); });
            if (phrases.length > 1 && /cannot align/.test(error.message)) {
                // Split in halves: a single phrase always aligns with its own answer.
                var middle = Math.ceil(phrases.length / 2);
                return Promise.all([
                    translateChunk(kind, phrases.slice(0, middle)),
                    translateChunk(kind, phrases.slice(middle))
                ]);
            }
            console.warn('Katakana Terminator: request failed, will retry later:', error && error.message);
            phrases.forEach(function (phrase) { noteFailure(kind, phrase); });
        });
    }

    function translatePending() {
        var now = Date.now();
        var pending = { english: [], reading: [] };

        queue.forEach(function (nodes, phrase) {
            var key = keyOf(phrase);
            if (labels.has(key)) {
                flushPhrase(phrase);
                return;
            }
            if (inflight.has(key)) return;
            var state = retryState.get(key);
            if (state && state.notBefore > now) return;
            pending[kindOf(phrase)].push(phrase);
        });

        Object.keys(pending).forEach(function (kind) {
            for (var i = 0; i < pending[kind].length; i += CHUNK_SIZE) {
                translateChunk(kind, pending[kind].slice(i, i + CHUNK_SIZE));
            }
        });
    }

    // ----- DOM -----------------------------------------------------------------------------------

    function inJapaneseContext(node) {
        // Kanji alone are also Chinese: annotate them only where the page says it is Japanese,
        // or the very text node already carries kana.
        if (KANA.test(node.nodeValue || '')) return true;
        var parent = node.parentElement;
        var holder = parent && parent.closest ? parent.closest('[lang]') : null;
        var lang = (holder ? holder.lang : doc.documentElement.lang) || '';
        return /^ja\b/i.test(lang);
    }

    function wrapMatch(node, match) {
        var ruby = doc.createElement('ruby');
        ruby.appendChild(doc.createTextNode(match[0]));
        var rt = doc.createElement('rt');
        rt.classList.add('katakana-terminator-rt');
        ruby.appendChild(rt);

        if (!queue.has(match[0])) queue.set(match[0], new Set());
        queue.get(match[0]).add(rt);

        // <span>start[カナ]end</span> => <span>start<ruby>カナ<rt data-rt="Kana"></rt></ruby>end</span>
        var after = node.splitText(match.index);
        node.parentNode.insertBefore(ruby, after);
        after.nodeValue = after.nodeValue.substring(match[0].length);
        return after;
    }

    function addRuby(node) {
        var text = node.nodeValue;
        if (!text || !node.parentNode) return null;

        var match = KATAKANA.exec(text);
        var kanji = KANJI_WORD.exec(text);
        if (kanji && !inJapaneseContext(node)) kanji = null;
        if (kanji) {
            // Drop a particle-looking trailing hiragana.
            var word = kanji[0].replace(/^([^ぁ-ゖ]+)(.*)$/, function (whole, head, tail) {
                return PARTICLE_START.test(tail) ? head : whole;
            });
            kanji = [word];
            kanji.index = KANJI_WORD.exec(text).index;
        }
        var chosen = null;
        if (match && (!kanji || match.index < kanji.index)) chosen = match;
        else if (kanji) chosen = kanji;
        return chosen ? wrapMatch(node, chosen) : null;
    }

    function scanTextNodes(node) {
        try {
            if (!node.parentNode || !doc.documentElement.contains(node)) return;
            // Mutation records hand over nodes from anywhere in the tree, so the exclusion is
            // checked on the ancestors too: text inside another script's <rt> (the Nom reading
            // of zoopdog-nom-ruby) or <ruby> must never get a label of its own.
            var holder = node.nodeType === Node.TEXT_NODE ? node.parentElement : node;
            if (holder && holder.closest && holder.closest(EXCLUDED_SELECTOR)) return;
            if (node.nodeType === Node.ELEMENT_NODE) {
                if (EXCLUDED_TAGS[node.tagName.toLowerCase()] || node.isContentEditable) return;
                if (node.shadowRoot) watchShadow(node.shadowRoot);
                Array.from(node.childNodes).forEach(scanTextNodes);
            } else if (node.nodeType === Node.TEXT_NODE) {
                var next = node;
                var guard = 0;
                while ((next = addRuby(next)) && guard++ < 10000) { /* keep splitting */ }
            } else if (node.nodeType === Node.DOCUMENT_FRAGMENT_NODE) {
                Array.from(node.childNodes).forEach(scanTextNodes);
            }
        } catch (error) {
            console.warn('Katakana Terminator: skipped a node:', error && error.message);
        }
    }

    // ----- styling (with a text fallback when ::before cannot be used) ---------------------------

    var STYLE = 'rt.katakana-terminator-rt::before { content: attr(data-rt); }';

    function installStyle() {
        try {
            if (typeof GM_addStyle === 'function') {
                GM_addStyle(STYLE);
                return;
            }
        } catch (error) { /* plain <style> below */ }
        try {
            var style = doc.createElement('style');
            style.textContent = STYLE;
            (doc.head || doc.documentElement).appendChild(style);
        } catch (error) { /* verifyStyle decides */ }
    }

    var verifyTimer = 0;
    function scheduleVerify() {
        if (verifyTimer || textMode) return;
        verifyTimer = setTimeout(function () {
            verifyTimer = 0;
            var rt = doc.querySelector('rt.katakana-terminator-rt[data-rt]');
            if (!rt) return;
            var content = '';
            try { content = getComputedStyle(rt, '::before').content; } catch (error) { return; }
            if (content && content !== 'none' && content !== 'normal') return;
            textMode = true;
            doc.querySelectorAll('rt.katakana-terminator-rt[data-rt]').forEach(function (element) {
                element.textContent = element.dataset.rt;
            });
        }, 150);
    }

    // ----- observation ---------------------------------------------------------------------------

    var newNodes = [];
    var observer = null;
    var watchedShadows = new WeakSet();

    function record(mutations) {
        mutations.forEach(function (mutation) {
            if (mutation.type === 'characterData') {
                if (mutation.target.parentNode) newNodes.push(mutation.target);
                return;
            }
            mutation.addedNodes.forEach(function (node) { newNodes.push(node); });
        });
    }

    function watchShadow(shadowRoot) {
        if (watchedShadows.has(shadowRoot)) return;
        watchedShadows.add(shadowRoot);
        observer.observe(shadowRoot, { childList: true, subtree: true, characterData: true });
        newNodes.push(shadowRoot);
    }

    function rescan() {
        try {
            record(observer.takeRecords());
            if (newNodes.length) {
                var nodes = newNodes;
                newNodes = [];
                nodes.forEach(scanTextNodes);
            }
            translatePending();
        } catch (error) {
            console.warn('Katakana Terminator: scan failed:', error && error.message);
        }
    }

    function main() {
        installStyle();
        observer = new MutationObserver(record);
        observer.observe(doc.documentElement, { childList: true, subtree: true, characterData: true });
        newNodes.push(doc.body || doc.documentElement);
        doc.addEventListener(RESCAN_EVENT, function () { newNodes.push(doc.body || doc.documentElement); });
        window.addEventListener('pageshow', function () { newNodes.push(doc.body || doc.documentElement); });
        rescan();
        // Doubles as the rate limiter for requests and as the retry clock for failed ones.
        setInterval(rescan, SCAN_INTERVAL_MS);
    }

    if (doc.body) main();
    else doc.addEventListener('DOMContentLoaded', main, { once: true });
})();
