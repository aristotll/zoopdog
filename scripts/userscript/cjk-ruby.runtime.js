    function inJapaneseContext(node) {
        // Kanji alone are also Chinese: annotate them only where the page says it is Japanese,
        // or the very text node already carries kana.
        if (KANA.test(node.nodeValue || '')) return true;
        var parent = node.parentElement;
        var holder = parent && parent.closest ? parent.closest('[lang]') : null;
        var lang = (holder ? holder.lang : doc.documentElement.lang) || '';
        return /^ja\b/i.test(lang);
    }

    function makeRt(kind, phrase, cls) {
        var rt = doc.createElement('rt');
        rt.classList.add('zd-cjk-rt', cls);
        var key = keyOf(kind, phrase);
        if (!queue.has(key)) queue.set(key, { kind: kind, phrase: phrase, rts: new Set() });
        queue.get(key).rts.add(rt);
        return rt;
    }

