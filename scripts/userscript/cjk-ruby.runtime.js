    var LONG_VOWELS = { 'ā': 'a', 'ī': 'i', 'ū': 'u', 'ē': 'e', 'ō': 'o' };

    // Returns '' when `text` is not plain Hepburn romaji. Long vowels (ō, ū …) become the katakana
    // long-vowel mark, the usual way to write a reading in katakana (トーキョー).
    function romajiToKatakana(text) {
        var input = String(text).toLowerCase().replace(/[āīūēō]/g, function (c) { return LONG_VOWELS[c] + 'ー'; });
        input = input.replace(/[\s·・\-]+/g, '');
        if (!input || /[^a-zー']/.test(input)) return '';

        var out = '';
        var i = 0;
        while (i < input.length) {
            var c = input[i];
            if (c === 'ー') { out += 'ー'; i++; continue; }
            if (c === "'") { i++; continue; }
            // Doubled consonant (tt, kk, ss, and tch) -> small tsu.
            if (i + 1 < input.length && c === input[i + 1] && VOWELS.indexOf(c) < 0 && c !== 'n') { out += 'ッ'; i++; continue; }
            if (c === 't' && input.substr(i + 1, 2) === 'ch') { out += 'ッ'; i++; continue; }
            var matched = false;
            for (var len = 3; len >= 1 && !matched; len--) {
                var chunk = input.substr(i, len);
                if (chunk.length !== len || !Object.prototype.hasOwnProperty.call(KANA_TABLE, chunk)) continue;
                if (chunk === 'n' && /^[aiueoy]/.test(input.substr(i + 1, 1))) continue; // na, ni… not ン
                out += KANA_TABLE[chunk];
                i += len;
                matched = true;
            }
            if (!matched) return '';
        }
        return out;
    }

