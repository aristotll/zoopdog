    // ----- translating ---------------------------------------------------------------------------

    function pickEndpoints(kind) {
        var now = Date.now();
        var list = ENDPOINTS[kind];
        var healthy = list.filter(function (endpoint) { return (endpointDownUntil[endpoint.id] || 0) <= now; });
        // Everything cooling down: try them all anyway rather than going silent.
        return healthy.length ? healthy : list;
    }

    function fetchLabels(kind, phrases) {
        var endpoints = pickEndpoints(kind);
        var lastError = new Error('no endpoint');
        function attempt(index) {
            if (index >= endpoints.length) return Promise.reject(lastError);
            var endpoint = endpoints[index];
            return request(endpoint.url(phrases)).then(function (text) {
                var json = JSON.parse(text.replace("'", '\u2019'));
                return endpoint.parse(phrases, json);
            }).then(function (result) {
                delete endpointDownUntil[endpoint.id];
                return result;
            }, function (error) {
                lastError = error;
                if (!/cannot align/.test(error.message)) {
                    endpointDownUntil[endpoint.id] = Date.now() + ENDPOINT_COOLDOWN_MS;
                }
                return attempt(index + 1);
            });
        }
        return attempt(0);
    }

    // Jyutping of each phrase: the library's per-character answers joined, okurigana skipped.
    function jyutpingLabels(phrases) {
        return Promise.all(phrases.map(function (phrase) {
            return convertText(phrase).then(function (items) {
                return items.map(function (item) { return item[1]; }).filter(Boolean).join(' ');
            });
        }));
    }

    function noteFailure(key) {
        var state = retryState.get(key) || { attempts: 0, notBefore: 0 };
        state.notBefore = Date.now() + RETRY_DELAYS_MS[Math.min(state.attempts, RETRY_DELAYS_MS.length - 1)];
        state.attempts++;
        retryState.set(key, state);
    }

    function translateChunk(kind, phrases) {
        phrases.forEach(function (phrase) { inflight.add(keyOf(kind, phrase)); });
        var work = kind === 'jyutping' ? jyutpingLabels(phrases) : fetchLabels(kind, phrases);
        return work.then(function (labelsForPhrases) {
            phrases.forEach(function (phrase, index) {
                var key = keyOf(kind, phrase);
                inflight.delete(key);
                retryState.delete(key);
                labels.set(key, labelsForPhrases[index] || ''); // '' = nothing to say; never ask again
                flushEntry(key);
            });
        }, function (error) {
            phrases.forEach(function (phrase) { inflight.delete(keyOf(kind, phrase)); });
            if (phrases.length > 1 && /cannot align/.test(error.message)) {
                // Split in halves: a single phrase always aligns with its own answer.
                var middle = Math.ceil(phrases.length / 2);
                return Promise.all([
                    translateChunk(kind, phrases.slice(0, middle)),
                    translateChunk(kind, phrases.slice(middle))
                ]);
            }
            console.warn('Zoopdog CJK Ruby: ' + kind + ' request failed, will retry later:', error && error.message);
            phrases.forEach(function (phrase) { noteFailure(keyOf(kind, phrase)); });
        });
    }

    function translatePending() {
        var now = Date.now();
        var pending = { english: [], reading: [], jyutping: [] };

        queue.forEach(function (entry, key) {
            if (labels.has(key)) {
                flushEntry(key);
                return;
            }
            if (inflight.has(key)) return;
            var state = retryState.get(key);
            if (state && state.notBefore > now) return;
            pending[entry.kind].push(entry.phrase);
        });

        Object.keys(pending).forEach(function (kind) {
            var size = kind === 'jyutping' ? 50 : CHUNK_SIZE;
            for (var i = 0; i < pending[kind].length; i += size) {
                translateChunk(kind, pending[kind].slice(i, i + size));
            }
        });
    }

