// ==UserScript==
// @name        Zoopdog Popup Dictionary__ZOOPDOG_NAME_SUFFIX__
// @description Vietnamese-English popup dictionary with Zoopdog pronunciation guide
// @author      Zoopdog Contributors
// @namespace   https://github.com/tabidots/zoopdog
// @match       *://*/*
// @grant       GM_addStyle
// @grant       GM_setValue
// @grant       GM_getValue__ZOOPDOG_LOCAL_GRANTS__
// @run-at      document-idle
// @version     __ZOOPDOG_VERSION__
// @updateURL   __ZOOPDOG_UPDATE_URL__
// @downloadURL __ZOOPDOG_DOWNLOAD_URL__
// ==/UserScript==

(function() {
  // Extension point for the -local build (see popupdict-local.runtime.js, the last runtime source):
  // null here, so the sources that follow may read it from their functions, and assigned by the
  // local runtime when it is concatenated in. Declared before the sources so no ordering of `var`
  // initialisers is involved.
  var zooLocal = null;

__ZOOPDOG_RUNTIME_SOURCES__

  // Generated by scripts/build-popupdict-userscript.js from zd-extension/db_src/vnedict2.json.
  // Also merges zd-extension/db_src/user_nom_entries/ shards and the optional chunom layer.
  // The dictionary is kept as its JSON text and parsed on first lookup (zooDictionary below): the
  // parse costs ~100-200 ms and ~40 MB of heap, which pages and frames that never see a hover
  // over a dictionary word should not pay.
  var ZOO_DICTIONARY_JSON = {"__ZOOPDOG_DICTIONARY__": true};
  var zooDictionaryParsed = null;

  function zooDictionary() {
    if (zooDictionaryParsed === null) {
      zooDictionaryParsed = JSON.parse(ZOO_DICTIONARY_JSON);
      ZOO_DICTIONARY_JSON = null; // drop the text reference once parsed
    }
    return zooDictionaryParsed;
  }

  // The first lookup would otherwise parse the dictionary in the middle of the user's first hover
  // (~100-180 ms of synchronous work). Once a started frame sees its first pointer activity, ONE
  // parse is queued for an idle moment instead, so that first hover usually finds it done. A real
  // lookup that comes first parses as before and this becomes a no-op (zooDictionary is
  // idempotent); frames that never see a pointer, and tiny frames (startPopup never runs there, so
  // none of the listeners that call this exists), never parse.
  var zooPrewarmScheduled = false;
  var ZOO_PREWARM_IDLE_TIMEOUT_MS = 2000;
  var ZOO_PREWARM_FALLBACK_MS = 200;

  function zooSchedulePrewarm() {
    if (zooPrewarmScheduled) return;
    zooPrewarmScheduled = true;
    var prewarm = function() { zooDictionary(); };
    if (typeof window.requestIdleCallback === 'function') {
      window.requestIdleCallback(prewarm, {timeout: ZOO_PREWARM_IDLE_TIMEOUT_MS});
    } else {
      window.setTimeout(prewarm, ZOO_PREWARM_FALLBACK_MS);
    }
  }
  // Number of dictionary keys, substituted at build time so diagnostics never walk the dictionary.
  var ZOO_KEY_COUNT = __ZOOPDOG_KEY_COUNT__;
  // Detailed `data-last-hover` strings cost a second caret lookup plus JSON work on every miss, so
  // they are opt-in: localStorage.setItem('zoopdogDebug', '1') on the page, then reload. Read once.
  var ZOO_DEBUG = (function() {
    try {
      return window.localStorage.getItem('zoopdogDebug') === '1';
    } catch (ignored) {
      return false;
    }
  })();
  var ZOO_MAX_WORDS = __ZOOPDOG_MAX_WORDS__;

  var ZOO_SETTINGS = {
    cjkDefinitionLineLength: 18,
    oldWordResetMs: 500
  };

  // Local-mode (add/edit Chu Nom entries via the book-translator reader server) lives in
  // scripts/userscript/local-*.js and popupdict-local.runtime.js -- see docs/local-mode.md. It is only
  // concatenated into the -local build, which ends by assigning `zooLocal = {...}` -- the one
  // seam between the two (declared above, before the runtime sources). In the public build it
  // stays null, so this file (and popup-render.js / popup-nom-review.js) is fully functional
  // without it.

  function addStyle(css) {
    if (typeof GM_addStyle === 'function') {
      GM_addStyle(css);
      return;
    }

    if (typeof GM !== 'undefined' && GM && typeof GM.addStyle === 'function') {
      GM.addStyle(css);
      return;
    }

    var head = document.getElementsByTagName('head')[0];
    if (!head) {
      return;
    }

    var style = document.createElement('style');
    style.type = 'text/css';
    style.textContent = css;
    head.appendChild(style);
  }

  function normalizeLookup(value) {
    return String(value || '')
      .replace(/[Đ\u00D0]/gu, 'đ')
      .normalize('NFC')
      .toLocaleLowerCase('vi-VN')
      .replace(/\s+/g, ' ')
      .trim();
  }

  function lookupContext(context) {
    var split = String(context || '').trim().split(/\s+/).filter(Boolean);
    var limit = Math.min(split.length, ZOO_MAX_WORDS);

    var dictionary = zooDictionary();
    for (var i = limit; i > 0; i--) {
      var candidate = normalizeLookup(split.slice(0, i).join(' '));
      if (Object.prototype.hasOwnProperty.call(dictionary, candidate) && dictionary[candidate]) {
        return {
          key: candidate,
          wordCount: i,
          results: dictionary[candidate]
        };
      }
    }

    return null;
  }

  // Element.contains() never crosses an open shadow boundary -- a video-caption or
  // translation-overlay widget (Eudict/欧路翻译, Immersive Translate) renders its actual text
  // inside one (see docs/build.md), so a plain contains() call from outside always answers
  // false for it even when the node is genuinely part of that widget's rendered tree. Walking
  // through `.host` wherever `.parentNode` runs out is the same climb Node.isConnected does
  // internally to cross that boundary.
  function zdContains(ancestor, node) {
    for (var current = node; current; current = current.parentNode || current.host) {
      if (current === ancestor) {
        return true;
      }
    }
    return false;
  }

  function elementContainsTextNode(element, textNode) {
    if (!element || !textNode || !textNode.parentNode) {
      return false;
    }
    return zdContains(element, textNode.parentNode);
  }

  function isExcludedTarget(target) {
    if (!target || target.nodeType !== Node.ELEMENT_NODE) {
      return false;
    }

    return !!target.closest(
      '#zoopdog-userscript-popup, #zoopdog-userscript-canvas, #zoopdog-userscript-modals, #zoopdog-userscript-selection-bar, #zoopdog-nom-review-selection-bar, #zoopdog-nom-review-export, input, textarea, select, option, button, script, style, [contenteditable="true"]'
    );
  }

  function getEventPoint(event) {
    var touch = null;

    if (event.changedTouches && event.changedTouches.length) {
      touch = event.changedTouches[0];
    } else if (event.touches && event.touches.length) {
      touch = event.touches[0];
    }

    if (touch) {
      return {x: touch.clientX, y: touch.clientY};
    }

    if (typeof event.clientX === 'number' && typeof event.clientY === 'number') {
      return {x: event.clientX, y: event.clientY};
    }

    return null;
  }

  // Set by startPopup once the popup exists, so a Shift press relayed to this frame can pin it.
  var zooPinPopup = null;
  var zooPopupStarted = false;

  // A frame of a few pixels (tracking pixel, ad slot, hidden widget) can never show a popup, yet
  // would still parse the dictionary on its first pointer event and wire a dozen listeners.
  var ZOO_MIN_FRAME_PX = 50;

  function zooIsTinyFrame() {
    try {
      if (window.top === window) return false;
    } catch (error) { /* a cross-origin top is still a different window: this is a frame */ }
    return window.innerWidth < ZOO_MIN_FRAME_PX || window.innerHeight < ZOO_MIN_FRAME_PX;
  }

  function main() {
    if (!document.body) {
      window.setTimeout(main, 50);
      return;
    }

    // The Shift relay is wired in every frame, tiny ones included: it also forwards a press to the
    // parent and to child frames, and a tiny middle frame must not cut that chain.
    var shiftRelay = zdCreateShiftRelay(window, function() {
      if (zooPinPopup) zooPinPopup();
    });

    // Capture phase, registered on window: other extensions (and pages) stop keydown from
    // propagating, and a bubble-phase listener then never sees Shift -- the pin silently fails.
    // `repeat` skips the auto-repeat of a held key, which would toggle the pin on and off.
    window.addEventListener('keydown', function(event) {
      if (event.which === 16 && !event.repeat) {
        shiftRelay.press();
      }
    }, true);

    if (!zooIsTinyFrame()) {
      startPopup();
      return;
    }

    // A frame can be resized after it loaded (an ad slot that opens): start once it is usable.
    var onFrameResize = function() {
      if (zooIsTinyFrame()) return;
      window.removeEventListener('resize', onFrameResize);
      startPopup();
    };
    window.addEventListener('resize', onFrameResize);
  }

  function startPopup() {
    if (zooPopupStarted) return;
    zooPopupStarted = true;

    addStyle("__ZOOPDOG_CSS__");
    if (zooLocal) {
      zooLocal.probe();
      zooLocal.wireSelectionBar();
    }
    zooMaybeRenderNomReviewExportPanel();
    zooWireNomReviewSelectionBar();

    // The canvas and popup DOM are built on the first hover (ensureUi), not here: every frame of
    // every page runs main(), and most never see a pointer move over text.
    var highlighter = null;
    var popup = null;
    var oldWord = null;

    function ensureUi() {
      if (popup) return;
      var canvas = new Highlighter();
      var result = new ResultPopup();
      highlighter = canvas;
      popup = result;
      result.body.addEventListener('click', function(event) {
        var button = event.target && event.target.closest ? event.target.closest('[data-zd-action]') : null;
        if (!button) return;
        event.preventDefault();
        var action = button.getAttribute('data-zd-action');
        var vi = button.getAttribute('data-zd-vi') || '';
        if (action === 'add-nom') {
          zooLocal.openNomModal(vi);
        } else if (action === 'set-order') {
          zooLocal.openNomOrderModal(vi);
        } else if (action === 'queue-nom-review') {
          zooQueueNomReview(vi, zooExtractNomReviewContext(highlighter.node, vi, highlighter.begin), button);
        }
      });
    }

    function clearActiveResult() {
      cancelPendingHover();
      if (!popup) return;
      highlighter.off();
      popup.hide();
    }

    // A hover that throws must never leave the popup silently dead. The error is logged and also
    // left on the popup element (`data-last-error`), which -- unlike the console of an isolated
    // userscript world -- is readable from the page and from DevTools' Elements panel.
    function mainListener(event, clearOnMiss) {
      try {
        return hoverLookup(event, clearOnMiss);
      } catch (error) {
        try {
          ensureUi();
          popup.container.dataset.lastError = String(error && error.stack || error).slice(0, 600);
          console.error('[Zoopdog popup] hover lookup failed:', error);
        } catch (ignored) { /* nothing more to do */ }
        return true;
      }
    }

    // Last outcome of a hover, on the popup element (`data-last-hover`): a userscript world's
    // console is hard to reach, the DOM is not. Written only when it changes.
    function noteHover(outcome) {
      if (popup.container.dataset.lastHover !== outcome) {
        popup.container.dataset.lastHover = outcome;
      }
    }

    // A page script or a translation extension may rebuild <body> (or clone the nodes in it)
    // after this script ran. The popup then keeps drawing into elements that are no longer in the
    // document -- every hover "works" and nothing is ever displayed. Re-attach them, and drop any
    // look-alike left behind by a clone, so the popup always lives in the current page.
    function ensureAttached() {
      [highlighter.canvas, popup.container].forEach(function(element) {
        if (!element.isConnected && document.body) {
          Array.prototype.slice.call(document.querySelectorAll('#' + element.id)).forEach(function(other) {
            if (other !== element) other.remove();
          });
          document.body.appendChild(element);
          popup.container.dataset.reattached = String((Number(popup.container.dataset.reattached) || 0) + 1);
        }
      });
    }

    function hoverLookup(event, clearOnMiss) {
      ensureUi();
      ensureAttached();
      if (popup.locked || isExcludedTarget(event.target)) {
        noteHover(popup.locked ? 'locked' : 'excluded');
        return true;
      }

      var mouse = getEventPoint(event);
      if (!mouse) {
        noteHover('nopoint');
        return true;
      }

      var origin = getWordAndContext(mouse);
      var element = document.elementFromPoint(mouse.x, mouse.y);

      // `origin.atPoint` means the word was found by testing which text the
      // pointer falls inside, so cross-checking it against elementFromPoint
      // would only reject it: a search result card lays a link-shaped click
      // target over the whole row, and that overlay -- what elementFromPoint
      // answers with -- does not contain the line being hovered at all,
      // which is why those rows never showed a popup.
      if (!origin || !origin.word ||
          (!origin.atPoint && !elementContainsTextNode(element, origin.node))) {
        var missKind = origin && origin.word ? 'notcontained' : 'noword';
        if (ZOO_DEBUG) {
          var caret = null;
          try { caret = zdCaretFromPoint(mouse); } catch (ignored) { /* reported as null */ }
          noteHover(missKind + ' origin=' + JSON.stringify(origin && {w: origin.word, o: origin.begin}) +
            ' caret=' + (caret && caret.node ? caret.node.nodeType + ':' + String(caret.node.data || '').slice(0, 12) + '@' + caret.offset : 'null') +
            ' pt=' + mouse.x + ',' + mouse.y + ' hasCPFP=' + !!document.caretPositionFromPoint);
        } else {
          noteHover(missKind);
        }
        if (clearOnMiss) {
          clearActiveResult();
        }
        return true;
      }

      // Checked before clearing: a multi-word match's highlight rect covers
      // every word in the phrase (e.g. "một câu" also covers "câu"), so the
      // mouse can sit over a *different* word than the one that produced the
      // current match without ever leaving that rect. Comparing words here,
      // instead of gating on the rect the way `mouseout` below does, is what
      // lets hovering onto "câu" re-look-up and find "câu nói" instead of
      // getting stuck on "một câu". Same word: nothing to do, and skipping
      // the clear/reshow keeps the popup from flickering while it sits still.
      if (origin.word === oldWord) {
        noteHover('same');
        return true;
      }

      clearActiveResult();
      oldWord = origin.word;
      var lookup = lookupContext(origin.context);
      if (!lookup) {
        noteHover(ZOO_DEBUG
          ? 'nolookup word=' + JSON.stringify(origin.word) + ' ctx=' + JSON.stringify(String(origin.context).slice(0, 60)) + ' keys=' + ZOO_KEY_COUNT
          : 'nolookup');
        window.setTimeout(function() {
          oldWord = null;
        }, ZOO_SETTINGS.oldWordResetMs);
        return true;
      }

      highlighter.on(origin.node, origin.begin, lookup.wordCount);
      popup.populate(lookup.results);
      noteHover('shown');
      popup.show(highlighter.highlights[0] || {
        left: mouse.x,
        right: mouse.x,
        top: mouse.y,
        bottom: mouse.y
      });

      window.setTimeout(function() {
        oldWord = null;
      }, ZOO_SETTINGS.oldWordResetMs);

      return true;
    }

    window.addEventListener('resize', function() {
      if (highlighter) highlighter.resize();
      clearActiveResult();
    });

    // Pinch-zoom and panning a zoomed page move the visual viewport without firing a window
    // 'scroll'/'resize', leaving the popup stranded (or half off screen) away from its word.
    if (window.visualViewport) {
      var onViewportChange = function() {
        if (!popup || popup.container.style.visibility !== 'visible' || !popup.viewChanged()) return;
        if (popup.locked) {
          var box = popup.container.getBoundingClientRect();
          popup.moveTo(box.left, box.top);
          popup.shownView = visibleViewport();
          return;
        }
        clearActiveResult();
      };
      window.visualViewport.addEventListener('resize', onViewportChange);
      window.visualViewport.addEventListener('scroll', onViewportChange);
    }

    function insidePopup(target) {
      return !!(target && target.nodeType === Node.ELEMENT_NODE &&
        target.closest('#zoopdog-userscript-popup'));
    }

    var lastTouchTime = 0;
    var touchMoved = false;
    var pointerTouchMoved = false;

    // A mouse fires pointermove far more often than the screen refreshes, and each hover walks
    // the DOM around the pointer. Moves are coalesced: the latest point is kept and looked up
    // once per animation frame. Only the fields the lookup reads are copied, because the event
    // object must not be relied on after its handler returns. Without requestAnimationFrame
    // (older embeds, test harnesses) the move runs immediately, as it always did.
    var pendingMove = null;
    var pendingFrame = 0;

    function cancelPendingHover() {
      pendingMove = null;
    }

    function scheduleHover(event) {
      if (typeof window.requestAnimationFrame !== 'function') {
        mainListener(event, false);
        return;
      }
      pendingMove = {
        target: event.target,
        clientX: event.clientX,
        clientY: event.clientY,
        pointerType: event.pointerType
      };
      if (pendingFrame) return;
      pendingFrame = window.requestAnimationFrame(function() {
        var move = pendingMove;
        pendingFrame = 0;
        pendingMove = null;
        if (move) mainListener(move, false);
      });
    }

    // Capture-phase so a scroll inside a nested scrollable container is seen
    // too (those don't bubble a 'scroll' event to window). But capture also
    // means this sees a scroll from *any* scrollable element on the page --
    // including ones with nothing to do with the highlighted word, such as an
    // auto-scrolling news ticker/carousel (e.g. jQuery SimplyScroll's
    // `.simply-scroll-clip`) that fires its own 'scroll' event dozens of
    // times a second purely from its own animation. Reacting to those
    // dismissed the popup within tens of milliseconds of ever showing it, on
    // any page carrying such a widget -- the "just blinks, can't show" bug.
    // Only a scroll of the document itself, or of a container the
    // highlighted word actually sits inside, can have moved that word.
    window.addEventListener('scroll', function(event) {
      var target = event.target;
      if (target && target !== document && target !== window && target !== document.documentElement &&
          highlighter && highlighter.node && !zdContains(target, highlighter.node)) {
        return;
      }
      clearActiveResult();
    }, true);
    // `mouseout` bubbles, so this fires at every boundary between inline
    // boxes -- and a Nôm-annotated page is made of those, one <ruby> per
    // word, each often inside a link inside a card. Crossing one of them
    // while the pointer is still inside the word that is showing is not the
    // mouse leaving anything: the clear hid the popup a frame after it
    // appeared, and the `oldWord` guard in mainListener then kept it from
    // coming back until the reset timer fired -- measured as visible/hidden
    // flipping every few hundred ms while the pointer sat on one word, which
    // is the flicker. Leaving the word, or the window, still clears.
    window.addEventListener('mouseout', function(event) {
      if (Date.now() - lastTouchTime <= 700) return;
      var point = getEventPoint(event);
      if (point && highlighter && highlighter.highlights.length && mouseInRects(point, highlighter.highlights)) {
        return;
      }
      clearActiveResult();
    });

    function touchListener(event) {
      cancelPendingHover();
      lastTouchTime = Date.now();
      if (touchMoved) {
        touchMoved = false;
        return true;
      }
      return mainListener(event, true);
    }

    function clickListener(event) {
      cancelPendingHover();
      if (Date.now() - lastTouchTime < 700) {
        return true;
      }
      return mainListener(event, true);
    }

    if ('PointerEvent' in window) {
      window.addEventListener('pointerdown', function(event) {
        zooSchedulePrewarm();
        if (event.pointerType === 'touch') {
          lastTouchTime = Date.now();
          pointerTouchMoved = false;
        }
      }, {passive: true});

      window.addEventListener('pointermove', function(event) {
        zooSchedulePrewarm();
        if (event.pointerType === 'touch') {
          lastTouchTime = Date.now();
          // A finger dragging inside the popup is scrolling the popup's own
          // content, not the page -- dismissing it would make it unscrollable.
          if (insidePopup(event.target)) return;
          pointerTouchMoved = true;
          clearActiveResult();
          return;
        }

        if (event.pointerType === 'mouse' || event.pointerType === 'pen') {
          scheduleHover(event);
        }
      }, {passive: true});

      window.addEventListener('pointerup', function(event) {
        cancelPendingHover();
        if (event.pointerType === 'touch') {
          lastTouchTime = Date.now();
        }

        if (event.pointerType === 'touch' && pointerTouchMoved) {
          pointerTouchMoved = false;
          return true;
        }
        mainListener(event, true);
      }, {passive: true});
    } else {
      window.addEventListener('mousemove', function(event) {
        zooSchedulePrewarm();
        scheduleHover(event);
      });

      window.addEventListener('touchstart', function() {
        zooSchedulePrewarm();
        touchMoved = false;
      }, {passive: true});

      window.addEventListener('touchmove', function(event) {
        if (insidePopup(event.target)) return;
        touchMoved = true;
        clearActiveResult();
      }, {passive: true, capture: true});

      window.addEventListener('touchend', touchListener, {passive: true});
      window.addEventListener('click', clickListener);
    }

    zooPinPopup = function() {
      // Shift is pressed constantly while typing and is relayed to every frame; with no popup
      // built yet there is nothing shown to pin, so the UI must not be created for it.
      if (!popup) return;
      highlighter.toggleLock();
      popup.toggleLock();
    };
  }

  main();
})();
