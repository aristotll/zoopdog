// Generated by scripts/build-jyutping-userscript.js from scripts/userscript/jyutping.runtime.js.
// Derived from CanCLID/inject-jyutping (BSD-2-Clause). Fault-tolerant rewrite of the page side:
//  - the converter loads in a Worker and falls back to the main thread (page CSP / blocked blob
//    workers) and to alternate CDNs; a failed load is retried with back-off, never given up on;
//  - every request has a deadline, so one stuck conversion cannot leave text without Jyutping;
//  - the page is re-swept after mutations, on a timer, and inside open shadow roots, so
//    late-loaded, re-rendered and edited text is picked up too;
//  - the <rt> label falls back to real text when the stylesheet cannot be applied.
(function () {
  'use strict';

  var FLAG = 'injectJyutping';
  var RESCAN_EVENT = 'inject-jyutping-rescan';
  var root = document.documentElement;

  // Running the script again (the context menu entry) only re-sweeps the first instance.
  if (root.dataset[FLAG]) {
    document.dispatchEvent(new CustomEvent(RESCAN_EVENT));
    return;
  }
  root.dataset[FLAG] = '1';

  var LIB_URLS = [
    'https://cdn.jsdelivr.net/npm/to-jyutping@3.1.1',
    'https://unpkg.com/to-jyutping@3.1.1/dist/index.js',
    'https://fastly.jsdelivr.net/npm/to-jyutping@3.1.1'
  ];
  var REQUEST_TIMEOUT_MS = 15000;
  var WORKER_READY_TIMEOUT_MS = 20000;
  var RETRY_DELAYS_MS = [2000, 5000, 15000, 30000, 60000];
  var SWEEP_INTERVAL_MS = 4000;
  var FLUSH_DELAY_MS = 30;
  var SKIP_TAGS = {
    RUBY: 1, RT: 1, RP: 1, OPTION: 1, TEXTAREA: 1, SCRIPT: 1, STYLE: 1, NOSCRIPT: 1,
    TEMPLATE: 1, INPUT: 1, SELECT: 1
  };
  var HAN_RE = /[\p{Unified_Ideograph}〆〇]/u;

  function hasHanChar(s) {
    return HAN_RE.test(s);
  }

  // Japanese, Korean and Vietnamese pages use Han characters with their own readings.
  function isTargetLang(locale) {
    var lang = String(locale || '').split('-', 1)[0].toLowerCase();
    return lang !== 'ja' && lang !== 'ko' && lang !== 'vi';
  }

  // ----- stylesheet ---------------------------------------------------------------------------

  var CSS = [
    'ruby.inject-jyutping > rt {',
    '  font-size: 0.74em; font-variant: initial; margin-left: 0.1em; margin-right: 0.1em;',
    '  text-transform: initial; letter-spacing: initial;',
    '}',
    'ruby.inject-jyutping > rt[data-content]::after { content: attr(data-content); }'
  ].join('\n');

  var textMode = false; // true once the stylesheet is known not to apply: rt gets real text

  function installStyle() {
    try {
      if (typeof GM_addStyle === 'function') {
        GM_addStyle(CSS);
        return;
      }
    } catch (error) { /* fall through to a plain <style> */ }
    try {
      var style = document.createElement('style');
      style.textContent = CSS;
      (document.head || document.documentElement).appendChild(style);
    } catch (error) { /* checked later by verifyStyle */ }
  }

  // A page CSP can block both GM_addStyle's injection and an inline <style>. Look at what the
  // browser really computed for the first label, and switch to text labels when it is not ours.
  function verifyStyle() {
    if (textMode) return;
    var rt = document.querySelector('ruby.inject-jyutping > rt[data-content]');
    if (!rt) return;
    var content = '';
    try { content = getComputedStyle(rt, '::after').content; } catch (error) { return; }
    if (content && content !== 'none' && content !== 'normal') return;
    try {
      var sheet = new CSSStyleSheet();
      sheet.replaceSync(CSS);
      document.adoptedStyleSheets = document.adoptedStyleSheets.concat([sheet]);
      content = getComputedStyle(rt, '::after').content;
      if (content && content !== 'none' && content !== 'normal') return;
    } catch (error) { /* use text labels */ }
    textMode = true;
    var labels = document.querySelectorAll('ruby.inject-jyutping > rt[data-content]');
    for (var i = 0; i < labels.length; i++) {
      labels[i].textContent = labels[i].dataset.content;
    }
  }

  // ----- converter: Worker first, main thread second, with retries -----------------------------

  function workerSource() {
    return '(' + function (urls) {
      var ready = false;
      var lastError = '';
      for (var i = 0; i < urls.length && !ready; i++) {
        try {
          importScripts(urls[i]);
          ready = typeof ToJyutping !== 'undefined';
        } catch (error) {
          lastError = String(error);
        }
      }
      postMessage({ ready: ready, error: lastError });
      onmessage = function (event) {
        var data = event.data;
        try {
          postMessage({ id: data.id, result: ToJyutping.getJyutpingList(data.text) });
        } catch (error) {
          postMessage({ id: data.id, error: String(error) });
        }
      };
    } + ')(' + JSON.stringify(LIB_URLS) + ')';
  }

  function withDeadline(promise, ms, what) {
    return new Promise(function (resolve, reject) {
      var timer = setTimeout(function () { reject(new Error(what + ' timed out')); }, ms);
      promise.then(function (value) { clearTimeout(timer); resolve(value); },
        function (error) { clearTimeout(timer); reject(error); });
    });
  }

  // Resolves to a function (text) => Promise<[char, jyutping|null][]>, or rejects.
  function startWorkerConverter() {
    return new Promise(function (resolve, reject) {
      var worker;
      try {
        worker = new Worker(URL.createObjectURL(new Blob([workerSource()], { type: 'text/javascript' })));
      } catch (error) {
        reject(error);
        return;
      }
      var nextId = 0;
      var pending = new Map();
      var settled = false;
      var readyTimer = setTimeout(function () { fail(new Error('worker not ready')); }, WORKER_READY_TIMEOUT_MS);

      function failAll(error) {
        pending.forEach(function (entry) { entry.reject(error); });
        pending.clear();
      }
      function fail(error) {
        clearTimeout(readyTimer);
        try { worker.terminate(); } catch (ignored) { /* already gone */ }
        failAll(error);
        if (!settled) {
          settled = true;
          reject(error);
        }
      }

      worker.addEventListener('error', function (event) {
        fail(new Error('worker error: ' + (event && event.message)));
      });
      worker.addEventListener('message', function (event) {
        var data = event.data;
        if (!data || typeof data !== 'object') return;
        if ('ready' in data) {
          clearTimeout(readyTimer);
          if (!data.ready) {
            fail(new Error('worker could not load the library: ' + data.error));
            return;
          }
          settled = true;
          resolve(function (text) {
            // A per-request deadline: a request the worker never answers must not hang forever.
            return withDeadline(new Promise(function (res, rej) {
              var id = ++nextId;
              pending.set(id, { resolve: res, reject: rej });
              worker.postMessage({ id: id, text: text });
            }), REQUEST_TIMEOUT_MS, 'conversion').catch(function (error) {
              if (/timed out/.test(error.message)) fail(error);
              throw error;
            });
          });
          return;
        }
        var entry = pending.get(data.id);
        if (!entry) return;
        pending.delete(data.id);
        if (data.error) entry.reject(new Error(data.error));
        else entry.resolve(data.result);
      });
    });
  }

  function downloadText(url) {
    if (typeof GM_xmlhttpRequest === 'function') {
      return new Promise(function (resolve, reject) {
        try {
          GM_xmlhttpRequest({
            method: 'GET',
            url: url,
            timeout: REQUEST_TIMEOUT_MS,
            onload: function (response) {
              if (response.status >= 200 && response.status < 300) resolve(response.responseText);
              else reject(new Error('HTTP ' + response.status));
            },
            onerror: function () { reject(new Error('network error')); },
            ontimeout: function () { reject(new Error('timeout')); }
          });
        } catch (error) {
          reject(error);
        }
      });
    }
    return withDeadline(fetch(url).then(function (response) {
      if (!response.ok) throw new Error('HTTP ' + response.status);
      return response.text();
    }), REQUEST_TIMEOUT_MS, 'download');
  }

  function startMainThreadConverter() {
    var index = 0;
    function attempt() {
      if (index >= LIB_URLS.length) return Promise.reject(new Error('library unavailable'));
      return downloadText(LIB_URLS[index++]).then(function (code) {
        var exported = {};
        new Function('exports', 'module', code)(exported, { exports: exported });
        if (typeof exported.getJyutpingList !== 'function') throw new Error('unexpected library shape');
        return function (text) {
          return Promise.resolve(exported.getJyutpingList(text));
        };
      }).catch(attempt);
    }
    return attempt();
  }

  var converter = null;        // Promise<function> while usable
  var converterFailures = 0;
  var retryNotBefore = 0;

  function getConverter() {
    if (converter) return converter;
    if (Date.now() < retryNotBefore) return null;
    var started = startWorkerConverter().catch(function () { return startMainThreadConverter(); });
    converter = started.then(function (convert) {
      converterFailures = 0;
      return convert;
    }, function (error) {
      converter = null;
      retryNotBefore = Date.now() + RETRY_DELAYS_MS[Math.min(converterFailures, RETRY_DELAYS_MS.length - 1)];
      converterFailures++;
      console.warn('[Inject Jyutping] converter unavailable, retrying later:', error && error.message);
      throw error;
    });
    converter.catch(function () { /* reported above; callers handle their own copy */ });
    return converter;
  }

  function convertText(text) {
    var ready = getConverter();
    if (!ready) return Promise.reject(new Error('converter backing off'));
    return ready.then(function (convert) {
      return convert(text);
    }).catch(function (error) {
      // A converter that timed out or died is dropped so the next sweep starts a fresh one.
      if (converter === ready) converter = null;
      throw error;
    });
  }

  // ----- DOM ----------------------------------------------------------------------------------

  function makeRuby(ch, pronunciation) {
    var ruby = document.createElement('ruby');
    ruby.classList.add('inject-jyutping');
    ruby.textContent = ch;
    var rt = document.createElement('rt');
    rt.lang = 'yue-Latn';
    rt.dataset.content = pronunciation;
    if (textMode) rt.textContent = pronunciation;
    ruby.appendChild(rt);
    return ruby;
  }

  var inflight = new WeakSet();
  var observedShadows = new WeakSet();
  var observer = null;

  function langOf(element) {
    var holder = element && element.closest ? element.closest('[lang]') : null;
    return holder ? holder.lang : (document.documentElement.lang || '');
  }

  function isSkippable(element) {
    return !!SKIP_TAGS[element.nodeName];
  }

  // Calls back for every convertible text node under `start`, including open shadow roots.
  function forEachText(start, callback) {
    if (!start) return;
    if (start.nodeType === Node.TEXT_NODE) {
      considerText(start, callback);
      return;
    }
    if (start.nodeType !== Node.ELEMENT_NODE && start.nodeType !== Node.DOCUMENT_FRAGMENT_NODE) return;
    if (start.nodeType === Node.ELEMENT_NODE && isSkippable(start)) return;
    if (start.nodeType === Node.ELEMENT_NODE && start.closest && start.closest('ruby,rt,option,textarea,script,style,noscript,template,select')) return;

    var walker = document.createTreeWalker(start, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT, {
      acceptNode: function (node) {
        if (node.nodeType === Node.TEXT_NODE) return NodeFilter.FILTER_ACCEPT;
        return isSkippable(node) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_SKIP;
      }
    });
    var node;
    while ((node = walker.nextNode())) {
      if (node.nodeType === Node.TEXT_NODE) {
        considerText(node, callback);
      } else if (node.shadowRoot) {
        observeShadow(node.shadowRoot);
        forEachText(node.shadowRoot, callback);
      }
    }
    if (start.nodeType === Node.ELEMENT_NODE && start.shadowRoot) {
      observeShadow(start.shadowRoot);
      forEachText(start.shadowRoot, callback);
    }
  }

  function considerText(node, callback) {
    if (inflight.has(node) || !hasHanChar(node.nodeValue || '')) return;
    var parent = node.parentNode;
    if (!parent || parent.nodeType !== Node.ELEMENT_NODE || isSkippable(parent)) return;
    if (!isTargetLang(langOf(parent))) return;
    callback(node);
  }

  function replaceNode(node, text, results) {
    if (!node.isConnected) return;
    if (node.nodeValue !== text) { // edited while converting: convert the new value instead
      enqueue(node);
      return;
    }
    var fragment = document.createDocumentFragment();
    for (var i = 0; i < results.length; i++) {
      var pair = results[i];
      fragment.appendChild(pair[1] === null ? document.createTextNode(pair[0]) : makeRuby(pair[0], pair[1]));
    }
    node.parentNode.replaceChild(fragment, node);
  }

  function convertNode(node) {
    if (inflight.has(node)) return;
    var text = node.nodeValue || '';
    inflight.add(node);
    convertText(text).then(function (results) {
      inflight.delete(node);
      replaceNode(node, text, results);
      scheduleVerify();
    }, function () {
      inflight.delete(node); // the periodic sweep will find this node again
    });
  }

  var queued = new Set();
  var flushTimer = 0;

  function enqueue(target) {
    queued.add(target);
    if (!flushTimer) flushTimer = setTimeout(flush, FLUSH_DELAY_MS);
  }

  function flush() {
    flushTimer = 0;
    var targets = Array.from(queued);
    queued.clear();
    targets.forEach(function (target) {
      if (target.isConnected !== false) forEachText(target, convertNode);
    });
  }

  var verifyTimer = 0;
  function scheduleVerify() {
    if (verifyTimer || textMode) return;
    verifyTimer = setTimeout(function () {
      verifyTimer = 0;
      verifyStyle();
    }, 150);
  }

  function observe(target) {
    observer.observe(target, { characterData: true, childList: true, subtree: true });
  }

  function observeShadow(shadowRoot) {
    if (observedShadows.has(shadowRoot)) return;
    observedShadows.add(shadowRoot);
    observe(shadowRoot);
  }

  function start() {
    installStyle();
    observer = new MutationObserver(function (changes) {
      for (var i = 0; i < changes.length; i++) {
        var change = changes[i];
        if (change.type === 'characterData') {
          if (change.target.parentNode) enqueue(change.target);
          continue;
        }
        for (var j = 0; j < change.addedNodes.length; j++) {
          var added = change.addedNodes[j];
          if (added.nodeType === Node.ELEMENT_NODE && added.classList.contains('inject-jyutping')) continue;
          enqueue(added);
        }
      }
    });
    observe(document.documentElement); // not just <body>: frameworks may swap the body itself

    enqueue(document.documentElement);
    document.addEventListener(RESCAN_EVENT, function () { enqueue(document.documentElement); });
    window.addEventListener('pageshow', function () { enqueue(document.documentElement); });
    // Safety net for anything the observer missed (shadow roots opened late, failed conversions).
    setInterval(function () {
      if (document.visibilityState === 'hidden') return;
      enqueue(document.body || document.documentElement);
    }, SWEEP_INTERVAL_MS);
  }

  if (document.body) start();
  else document.addEventListener('DOMContentLoaded', start, { once: true });
})();
