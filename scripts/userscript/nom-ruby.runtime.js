// ==UserScript==
// @name        Zoopdog Nom Ruby__ZOOPDOG_NAME_SUFFIX__
// @description Add Chu Nom ruby annotations to Vietnamese text using Zoopdog dictionary data
// @author      Zoopdog Contributors
// @namespace   https://github.com/tabidots/zoopdog
// @match       *://*/*
// @exclude     http://127.0.0.1:8770/*
// @exclude     http://localhost:8770/*
// @grant       GM_addStyle
// @grant       GM_registerMenuCommand
// @version     __ZOOPDOG_VERSION__
// @updateURL   __ZOOPDOG_UPDATE_URL__
// @downloadURL __ZOOPDOG_DOWNLOAD_URL__
// ==/UserScript==

(function() {
  'use strict';

  // ===== zd-extension/js/zd-nom-match.js =====
  __ZOOPDOG_NOM_MATCH_ENGINE__

  // ===== scripts/userscript/overlay-labels.js =====
  __ZOOPDOG_OVERLAY_LABELS__

  // ===== scripts/userscript/zd-userscript-common.js =====
  __ZOOPDOG_USERSCRIPT_COMMON__

  // ===== zd-extension/js/zd-words.js =====
  __ZOOPDOG_WORDS__

  // Generated by scripts/build-nom-userscript.js from zd-extension/db_src/vnedict2.json.
  // Also merges user_nom_entries/ shards and optional mdx_nom.json and chunom data.
  // Dictionary entries embedded: __ZOOPDOG_ENTRY_COUNT__
  var NOM_MAP_JSON = {"__ZOOPDOG_NOM_MAP__": true};

  // Exact spelling -> its own display order, from user_nom_order.jsonc rows marked
  // `"caseSensitive": true` (e.g. the surname "Đỗ", read differently from the ordinary word
  // "đỗ"). See zd-nom-match.js's zdCreateNomMatcher for where this is checked.
  var CASE_SENSITIVE_NOM_MAP_JSON = {"__ZOOPDOG_CASE_SENSITIVE_NOM_MAP__": true};

  var SETTINGS = {
    // "safe" annotates longer ASCII-only Vietnamese words while still skipping
    // short/common English words such as "an", "to", or "no".
    // Set to true to annotate every ASCII-only entry, or false to skip all of them.
    annotateAsciiTerms: 'safe',
    // False shows only the first known Chu Nom candidate as ruby; all candidates stay in title.
    showAllVariants: false,
    // The safety-net poll runs this often while pages keep changing, and backs off to
    // rescanIdleMaxMs while consecutive polls find nothing to do.
    rescanIntervalMs: 500,
    rescanIdleMaxMs: 5000,
    // A scan that runs longer than this yields to the page and continues in a later task.
    scanSliceMs: 12,
    scanIdleTimeoutMs: 100
  };

  var doc = document;
  var newNodes = new Set();
  var changedNodes = new Set();
  // A page that streams text rewrites its own text nodes in place. The nodes this script
  // inserted next to such a node still hold the previous text, so they are remembered here
  // and dropped before the rewritten node is annotated again.
  var injections = new WeakMap();
  // Both maps are embedded as JSON text. Parsing them and building the matcher index cost tens of
  // milliseconds and several MB, so that waits for the first text node that holds a word
  // character -- a page with none (CJK, numbers, an empty shell) never pays it.
  var nomMatcherInstance = null;
  function getNomMatcher() {
    if (nomMatcherInstance === null) {
      nomMatcherInstance = zdCreateNomMatcher(
        JSON.parse(NOM_MAP_JSON), SETTINGS, JSON.parse(CASE_SENSITIVE_NOM_MAP_JSON));
      NOM_MAP_JSON = null; // the text is no longer needed once the index is built
      CASE_SENSITIVE_NOM_MAP_JSON = null;
    }
    return nomMatcherInstance;
  }
  // A video-caption or translation-overlay widget (Eudict/欧路翻译, Immersive Translate) renders
  // its actual on-screen text inside its own *open* shadow root, to keep the host page's CSS
  // from leaking in. That content is real, painted DOM, but it is not part of any element's
  // childNodes and a MutationObserver rooted at document.body never sees mutations inside it --
  // both the initial scan and the observer have to be told about each shadow root separately.
  // Declared here (not inside main()) so scanTextNodes and the attachShadow patch below can
  // both reach the same observer instance.
  var observer;
  var observedShadowRoots = new WeakSet();
  // Same roots as a list, so the toggle button can unannotate and re-observe every one of them.
  var shadowRootList = [];
  // Set by main(); the toggle button drives these.
  var rescanNow = null;
  var enabled = true;
  // A big scan runs in time slices (see runScanJob). `scanJob` is the scan in flight; bumping
  // `scanGeneration` supersedes it (disable, re-render); `scanPasses` counts the queue
  // drains made since the last fresh rescan, so MAX_RESCAN_PASSES bounds a sliced scan as a whole.
  var scanJob = null;
  // The scan job's zdContainerBoundary cache while a slice runs (see runScanJob); null outside a slice.
  var boundaryCache = null;
  var scanGeneration = 0;
  var scanPasses = 0;
  var scanContinuation = null;
  // The webfont is its own sheet: the -local build embeds the whole font here (~14MB of base64),
  // which every document that parses it pays for -- so it is added only once a ruby is about to
  // be created (ensureFontFace), never to a page with nothing to annotate, and never again per
  // shadow root: a document-level @font-face already applies inside shadow trees.
  function fontFaceCss() {
    return [
      '@font-face {',
      "  font-family: 'Zoopdog Nom Na Tong';",
      "  src: __ZOOPDOG_NOM_FONT_SRC__;",
      '  font-display: swap;',
      '}'
    ].join('\n');
  }

  // ===== per-site fixes and renderer choice ======================================================
  // `ruby` (default): annotations are <ruby> elements in the page text. `overlay`: the page is never
  // touched, labels are drawn in a layer above it (overlay-labels.js) -- for sites whose own scripts or CSS
  // fight inline <ruby>. A fix only applies on the hosts it names.
  var SITE_FIXES = [
    {
      host: /(^|\.)reddit\.com$/,
      // Reddit's post previews reset every descendant with `all: revert; display: inline !important`, which
      // flattens <ruby>/<rt> into inline text. Outrank it (it is (0,2,2)) with the same !important.
      css: [
        ':root:root ruby.zoopdog-nom-ruby { display: ruby !important; }',
        ':root:root ruby.zoopdog-nom-ruby > rt.zoopdog-nom-rt { display: ruby-text !important; }'
      ].join('\n')
    }
  ];
  var MODE_RULES = [
    { host: /(^|\.)zhihu\.com$/, mode: 'overlay' }
  ];
  // Rules injected at build time into the -local build only (scripts/lib/userscript.js, readLocalSiteRules);
  // the published build gets an empty list. They never appear in this source.
  var LOCAL_SITE_RULES = __ZOOPDOG_LOCAL_SITE_RULES__;
  LOCAL_SITE_RULES.forEach(function(rule) {
    var host = new RegExp(rule.host);
    SITE_FIXES.push({ host: host, css: rule.css, perWord: rule.perWord });
    if (rule.mode) MODE_RULES.push({ host: host, mode: rule.mode });
  });
  var MODE_KEY = 'zoopdogNomMode';

  function pickSiteFix() {
    for (var i = 0; i < SITE_FIXES.length; i++) {
      if (SITE_FIXES[i].host.test(window.location.hostname)) return SITE_FIXES[i];
    }
    return {};
  }

  function chooseMode() {
    try {
      var saved = window.localStorage.getItem(MODE_KEY + ':' + window.location.hostname);
      if (saved === 'ruby' || saved === 'overlay') return saved;
    } catch (error) { /* storage blocked: use the table */ }
    for (var i = 0; i < MODE_RULES.length; i++) {
      if (MODE_RULES[i].host.test(window.location.hostname)) return MODE_RULES[i].mode;
    }
    return 'ruby';
  }

  var siteFix = pickSiteFix();
  var mode = chooseMode();
  var overlay = null;

  var rubyCss = [
    'ruby.zoopdog-nom-ruby { ruby-position: over; }',
    'ruby.zoopdog-nom-ruby > rt.zoopdog-nom-rt {',
    '  color: #B6638F;',
    "  font-family: 'Zoopdog Nom Na Tong', sans-serif;",
    '  font-size: 0.65em;',
    '  font-weight: 600;',
    '  line-height: 1;',
    '  user-select: none;',
    '}'
  ].join('\n') + '\n' + (siteFix.css || '');

  var fontFaceAdded = false;

  // The font src is a github raw-styled URL in the committed build (small file, but blocked by
  // font-src CSP on sites like YouTube -- document.fonts then reports this family as "error" and
  // every rare Nom glyph silently falls back to invisible tofu in sans-serif) and a `data:` URI
  // embedding the whole font in the -local build (large file, but immune to font-src since there
  // is no network fetch to block). See docs/build.md.
  function ensureFontFace() {
    if (fontFaceAdded) {
      return;
    }
    fontFaceAdded = true;
    addStyle(fontFaceCss());
  }

  // Eudict's caption overlay caps each language row at a few lines' height (`max-height: 3.6em`,
  // `overflow: hidden`). A ruby line is taller than a plain one, so an annotated row no longer
  // fits: its lower lines are clipped, and because the row centres its content the overflow
  // spills upward over the row above. Only the overlay's own rows are lifted, and only inside
  // shadow roots -- the overlay's box is anchored at the bottom, so it simply grows upward.
  var captionCss = [
    '.eudic-chrome-extension-video-src,',
    '.eudic-chrome-extension-video-dest {',
    '  max-height: none !important;',
    '  overflow: visible !important;',
    '}'
  ].join('\n');

  // ===== scripts/userscript/nom-ruby-scan.js =====
__ZOOPDOG_NOM_SCAN__

  function watchShadowRoot(root) {
    if (watchShadowRootFor(root)) {
      scanTextNodes(root);
    }
  }

  // Registers `root` once (style, observer). True when it is new and should be scanned now.
  function watchShadowRootFor(root) {
    if (observedShadowRoots.has(root)) {
      return false;
    }
    observedShadowRoots.add(root);
    shadowRootList.push(root);
    addStyleToRoot(root, rubyCss + '\n' + captionCss);
    if (observer && enabled) {
      observer.observe(root, {characterData: true, childList: true, subtree: true});
    }
    return enabled;
  }

  // Catches a shadow root the moment it is created, for the host element this script has not
  // walked past yet (a widget that attaches its shadow root only once the video/track it
  // depends on is ready, well after this script's own initial scan). `watchShadowRoot` above
  // handles a shadow root that already existed when its host was scanned; this handles one that
  // does not exist yet. Every open shadow root gets watched, from any script or extension on
  // the page -- not only known caption widgets -- since there is no reliable way to tell in
  // advance which ones will carry annotatable text.
  function patchAttachShadow() {
    if (typeof Element === 'undefined' || !Element.prototype.attachShadow) {
      return;
    }
    var original = Element.prototype.attachShadow;
    function watchCreated(root) {
      if (root.mode === 'open') {
        watchShadowRoot(root);
      }
      return root;
    }
    // A Proxy keeps `attachShadow.toString()` reading as native code. A plain wrapper function
    // shows its source, which bot-detection scripts (Cloudflare Turnstile) read as tampering.
    if (typeof Proxy === 'function' && typeof Reflect === 'object') {
      Element.prototype.attachShadow = new Proxy(original, {
        apply: function(target, thisArg, args) {
          return watchCreated(Reflect.apply(target, thisArg, args));
        }
      });
      return;
    }
    Element.prototype.attachShadow = function(init) {
      return watchCreated(original.call(this, init));
    };
  }

  // A Cloudflare challenge page ("Just a moment...") or its Turnstile frame. The challenge
  // checks its own page for foreign DOM changes and patched built-ins, and never finishes when
  // an annotator has touched it (the verification loops with "taking longer"), so this script
  // does nothing there. The challenge reloads into the real page once passed, which is then
  // annotated as usual. The title is localized, so the page is recognised by its markup.
  var CHALLENGE_PAGE_SELECTOR = [
    'script[src*="/cdn-cgi/challenge-platform/"][src*="/orchestrate/"]',
    '#challenge-error-text',
    '#challenge-success-text',
    '#challenge-body-text'
  ].join(',');

  function isCloudflareChallenge() {
    if (window.location && window.location.hostname === 'challenges.cloudflare.com') {
      return true;
    }
    return !!doc.querySelector(CHALLENGE_PAGE_SELECTOR);
  }

  // ===== scripts/userscript/nom-ruby-annotate.js =====
__ZOOPDOG_NOM_ANNOTATE__

  function addStyle(css) {
    if (typeof GM_addStyle === 'function') {
      GM_addStyle(css);
      return;
    }

    var head = doc.getElementsByTagName('head')[0];
    if (!head) {
      return;
    }

    var style = doc.createElement('style');
    style.type = 'text/css';
    style.textContent = css;
    head.appendChild(style);
  }

  // Shadow DOM's whole point is that a page's own <style> (however it got there, GM_addStyle
  // included) does not reach inside it -- so the ruby/rt rules that make an annotation visible
  // have to be appended a second time, directly into each shadow root this script watches, or
  // the annotation renders with no font/color/positioning at all despite being present in the
  // DOM (correct markup, invisible paint -- see docs/build.md).
  function addStyleToRoot(root, css) {
    var style = doc.createElement('style');
    style.textContent = css;
    root.appendChild(style);
  }

  function registerModeMenu() {
    if (typeof GM_registerMenuCommand !== 'function') return;
    try {
      var next = mode === 'ruby' ? 'overlay' : 'ruby';
      GM_registerMenuCommand('Nom Ruby on ' + window.location.hostname + ': ' + mode + ' -> ' + next + ' (reloads)', function() {
        try { window.localStorage.setItem(MODE_KEY + ':' + window.location.hostname, next); } catch (error) { /* ignore */ }
        location.reload();
      });
    } catch (error) { /* no menu */ }
  }

  function main() {
    if (!doc.body) {
      window.setTimeout(main, 50);
      return;
    }
    // The challenge markup is parsed after <body> exists; wait for the document so it is seen.
    if (doc.readyState === 'loading') {
      doc.addEventListener('DOMContentLoaded', main, {once: true});
      return;
    }
    if (isCloudflareChallenge()) {
      return;
    }

    if (mode === 'overlay') {
      overlay = zdCreateOverlay(doc, window, {
        id: 'zoopdog-nom-overlay',
        documentAnchored: /(^|\.)zhihu\.com$/.test(window.location.hostname),
        onStats: function(stats) { doc.documentElement.dataset.zoopdogNomOverlay = stats; }
      });
      if (typeof window.addEventListener === 'function') {
        window.addEventListener('scroll', overlay.schedule, {capture: true, passive: true});
        window.addEventListener('resize', overlay.schedule, {passive: true});
      }
    } else {
      try { addStyle(rubyCss); } catch (error) { doc.documentElement.dataset.zoopdogNomError = String(error); }
    }
    try { doc.documentElement.dataset.zoopdogNomMode = mode; } catch (error) { /* beacon only */ }
    registerModeMenu();

    newNodes.add(doc.body);

    try { patchAttachShadow(); } catch (error) { doc.documentElement.dataset.zoopdogNomError = String(error); }

    var frameScheduled = false;

    // A caption widget replaces its whole line for every cue. Waiting for the interval tick
    // paints the plain line first and swaps in the ruby up to rescanIntervalMs later, which
    // shows as flicker. A frame callback runs before the next paint, so the line is annotated
    // before it is ever shown; the poll stays as the fallback (hidden tabs pause frames).
    function scheduleFrameScan() {
      if (frameScheduled || typeof window.requestAnimationFrame !== 'function') {
        return;
      }
      frameScheduled = true;
      window.requestAnimationFrame(function() {
        frameScheduled = false;
        rescanTextNodes();
      });
    }

    observer = new MutationObserver(function(mutationList) {
      mutationHandler(mutationList);
      scheduleFrameScan();
      poll.wake();
    });
    observer.observe(doc.body, {characterData: true, childList: true, subtree: true});

    // One failing pass (a page-specific node that trips the scanner) must not stop the poll, the
    // toggle button or later passes: the error is recorded on <html data-zoopdog-nom-error> for
    // diagnosis (a userscript's console is not reachable from the page or a phone) and retried.
    // Returns whether the pass found anything to do (a failed one counts, so it is retried soon).
    function rescanTextNodes() {
      try {
        return rescanTextNodesUnsafe();
      } catch (error) {
        try {
          doc.documentElement.dataset.zoopdogNomError = String(error && error.stack || error).slice(0, 400);
          console.error('[Zoopdog Nom]', error);
        } catch (ignored) { /* nothing more to do */ }
        return true;
      } finally {
        boundaryCache = null;
      }
    }

    function rescanTextNodesUnsafe() {
      if (!enabled) {
        return false;
      }
      // This call supersedes a continuation that is still waiting for its turn.
      cancelScanContinuation();
      mutationHandler(observer.takeRecords());
      var worked = changedNodes.size > 0 || newNodes.size > 0 || scanJob !== null;

      if (changedNodes.size) {
        var changed = [...changedNodes];
        changedNodes.clear();
        changed.forEach(refreshChangedNode);
      }

      // A pass can queue more work itself (the tail of a following node after a match that
      // spans nodes), so drain until it settles -- bounded, leftovers wait for the next tick.
      // A scan that outlasts its time slice stays in `scanJob` and continues in a later task.
      if (!scanJob) {
        scanPasses = 0;
      }
      var deadline = scanDeadline();
      var paused = false;
      while (scanJob || (newNodes.size && scanPasses < MAX_RESCAN_PASSES)) {
        if (!scanJob) {
          scanJob = createScanJob(outermostNodes([...newNodes]));
          newNodes.clear();
          scanPasses++;
        }
        if (!runScanJob(scanJob, deadline)) {
          paused = true;
          break;
        }
        scanJob = null;
      }

      // Everything queued on the observer since the records were taken above is this script's
      // own annotation work (page code cannot run in between), and nothing in it needs another
      // look: rescanning the parent of every ruby just inserted only re-verified text the pass
      // had already exhausted.
      observer.takeRecords();
      if (overlay) overlay.schedule(); // page layout may have moved the words
      if (paused) scheduleScanContinuation();
      return worked;
    }

    rescanNow = rescanTextNodes;
    // The button first: it is how the user sees that the script is alive at all.
    if (window.top === window) {
      try { createToggleButton(); } catch (error) {
        doc.documentElement.dataset.zoopdogNomError = String(error && error.stack || error).slice(0, 400);
      }
    }
    poll.start();
    rescanTextNodes();
  }

  // ===== scripts/userscript/nom-ruby-lifecycle.js =====
__ZOOPDOG_NOM_LIFECYCLE__

  if (typeof NodeList.prototype.forEach === 'undefined') {
    NodeList.prototype.forEach = function(callback, thisArg) {
      thisArg = thisArg || window;
      for (var i = 0; i < this.length; i++) {
        callback.call(thisArg, this[i], i, this);
      }
    };
  }

  main();
})();
